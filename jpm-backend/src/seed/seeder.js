export const seedInitialData = async () => {
    try {
        await Product.deleteMany();
        await Category.deleteMany();
        await User.deleteMany();

        const productsWithSlugs = sampleProducts.map((p) => ({
            ...p,
            slug: slugify(p.title, { lower: true, strict: true }),
        }));

        await Category.insertMany(categories);
        await Product.insertMany(productsWithSlugs);
        await User.create([
            {
                name: 'Demo Admin User',
                email: 'admin@jpmstore.com',
                password: 'Password123!',
                role: 'admin',
            },
            {
                name: 'John Doe Client',
                email: 'john@example.com',
                password: 'Password123!',
                role: 'user',
            },
        ]);
        logger.info(`🎉 Database successfully seeded with ${categories.length} categories, ${productsWithSlugs.length} products, and demo users!`);
    } catch (error) {
        logger.error(`❌ Data Seeding Error: ${error.message}`);
    }
};

const runSeederCLI = async () => {
    try {
        const mongoUri = process.env.MONGODB_URI || 'mongodb://localhost:27017/jpm_store';
        await mongoose.connect(mongoUri);
        await seedInitialData();
        process.exit();
    } catch (err) {
        logger.error(`❌ CLI Seeder Error: ${err.message}`);
        process.exit(1);
    }
};

if (process.argv[1] && process.argv[1].endsWith('seeder.js')) {
    runSeederCLI();
}
